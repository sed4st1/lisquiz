class CurriculumService:
    """
    Сервис доступа к государственному каталогу тем ФРП РФ (edsoo.ru).
    Обеспечивает поиск и фильтрацию официальных тем уроков для создания викторин.
    """

    def __init__(self):
        self._topics = FRP_CURRICULUM_DATABASE

    def get_topics(
        self,
        subject: Optional[str] = None,
        grade: Optional[int] = None,
        query: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Фильтрация тем по предмету (с поддержкой синонимов), классу и интеллектуальному поиску.
        """
        results = self._topics

        if subject:
            subj_lower = subject.strip().lower()
            allowed = SUBJECT_ALIASES.get(subj_lower, [subj_lower])
            results = [t for t in results if t["subject"].lower() in allowed]

        if grade is not None:
            results = [t for t in results if t["grade"] == grade]

        if query and query.strip():
            raw_q = query.strip().lower()

            # 1. Прямой поиск подстроки
            direct_matches = [
                t for t in results
                if raw_q in t["topic"].lower()
                or raw_q in t["section"].lower()
                or raw_q in t.get("description", "").lower()
                or any(raw_q in kw.lower() for kw in t.get("keywords", []))
            ]
            if direct_matches:
                return direct_matches

            # 2. Интеллектуальный токенизированный поиск (удаляет стоп-слова: для, класс, №, п/п)
            import re
            cleaned = re.sub(r'[^\w\s]', ' ', raw_q)
            tokens = [t.strip() for t in cleaned.split() if t.strip()]
            stop_words = {
                'для', 'по', 'в', 'во', 'на', 'о', 'об', 'обо', 'с', 'со', 'и', 'к', 'ко',
                'из', 'от', 'до', 'за', 'у', 'под', 'над', 'при', 'про',
                'класс', 'класса', 'классы', 'классу', 'классом', 'кл',
                'п', 'пп', 'номер', 'урок', 'урока', 'уроку', 'тема', 'теме', 'тему',
                'тест', 'квиз', 'задание', 'викторина'
            }
            meaningful_tokens = [t for t in tokens if t not in stop_words and not t.isdigit()]
            target_tokens = meaningful_tokens if meaningful_tokens else [t for t in tokens if not t.isdigit()]
            if not target_tokens:
                target_tokens = tokens

            def score_topic(t: Dict[str, Any]) -> int:
                haystack = f"{t['topic']} {t['section']} {t.get('description', '')} {' '.join(t.get('keywords', []))}".lower()
                return sum(1 for tok in target_tokens if tok in haystack)

            scored = [(score_topic(t), t) for t in results]
            min_matches = 1 if len(target_tokens) <= 2 else max(1, len(target_tokens) - 1)
            filtered = [t for score, t in scored if score >= min_matches]
            filtered.sort(key=lambda item: score_topic(item), reverse=True)
            if filtered:
                return filtered
            return []

        return results

    def get_topic_by_id(self, topic_id: str) -> Optional[Dict[str, Any]]:
        for t in self._topics:
            if t["id"] == topic_id:
                return t
        return None


curriculum_service = CurriculumService()
